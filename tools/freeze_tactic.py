"""Freeze an accepted public-command profile as reproducible Godot QA data."""
import argparse
import json
from pathlib import Path


def gd(value):
    if isinstance(value, dict):
        return "{" + ", ".join(json.dumps(k) + ": " + gd(v) for k, v in value.items()) + "}"
    if isinstance(value, list):
        return "[" + ", ".join(gd(v) for v in value) + "]"
    return json.dumps(value, ensure_ascii=False)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("report", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--profile", default="siege")
    args = parser.parse_args()
    results = json.loads(args.report.read_text(encoding="utf-8-sig"))
    result = next(item for item in results if item["profile"] == args.profile)
    if result["phase"] != "won" or result["rejected_commands"] or result["occupancy_violations"]:
        raise SystemExit("Only a winning, fully accepted, overlap-free profile can be frozen.")
    expected = {k: result[k] for k in (
        "seed", "phase", "time", "core_hp", "alive", "awake", "living_enemies",
        "state_hash", "accepted_commands", "rejected_commands", "occupancy_violations",
        "ally_friendly_fire_hits", "ally_friendly_fire_hp",
    )}
    expected.update(result["stats"])
    lines = [
        "extends RefCounted", "",
        "# Frozen v0.2 public commands; generated by tools/freeze_tactic.py.",
        "# Gameplay snapshot scope is documented in victory_check.gd.",
        "static func expected() -> Dictionary:", "\treturn " + gd(expected), "",
        "static func commands() -> Array:", "\treturn [",
    ]
    for operation in result["operations"]:
        order = {k: operation[k] for k in ("step", "ids", "kind", "data")}
        position = order["data"].get("position")
        line = gd(order)
        if position is not None:
            line = line.replace('"position": ' + gd(position), '"position": Vector2(' + ", ".join(map(repr, position)) + ")")
        lines.append("\t\t" + line + ",")
    lines += ["\t]", ""]
    args.output.write_text("\n".join(lines), encoding="utf-8")
    print(f"FROZEN {len(result['operations'])} commands / hash {result['state_hash']} / {args.output}")


if __name__ == "__main__":
    main()
