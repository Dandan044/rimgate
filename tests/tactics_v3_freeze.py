"""Freeze a fresh v3 public-command run; never reuse an earlier version hash."""
import argparse
import hashlib
import json
from pathlib import Path


def gd(value):
    if isinstance(value, dict):
        return "{" + ", ".join(json.dumps(k) + ": " + gd(v) for k, v in value.items()) + "}"
    if isinstance(value, list):
        return "[" + ", ".join(gd(v) for v in value) + "]"
    return json.dumps(value, ensure_ascii=False)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("report", type=Path)
    parser.add_argument("--profile", default="siege")
    args = parser.parse_args()
    result = next(item for item in json.loads(args.report.read_text(encoding="utf-8-sig")) if item["profile"] == args.profile)
    if result["phase"] != "won" or result["time"] != 480 or result["rejected_commands"] or result["occupancy_violations"] or result["stats"]["enemy_spawned"] != 24:
        raise SystemExit("Only a full current-standard-world victory with every command accepted and no overlap can be frozen.")
    result["ai_contract"] = "demo_v0.3_cover_intervals_pressure_reload"
    result["frozen_source"] = str(args.report).replace("\\", "/")
    result["source_sha256"] = {name: hashlib.sha256(Path(name).read_bytes()).hexdigest() for name in ["scripts/sim/battle_config.gd", "scripts/sim/state.gd", "scripts/sim/weapon_pose.gd", "scripts/sim/world.gd", "scripts/sim/unit_system.gd", "scripts/sim/combat_system.gd"]}
    expected = {k: result[k] for k in ["seed", "phase", "time", "core_hp", "alive", "awake", "living_enemies", "state_hash", "accepted_commands", "rejected_commands", "occupancy_violations", "ally_friendly_fire_hits", "ally_friendly_fire_hp"]}
    expected.update(result["stats"])
    lines = ["extends RefCounted", "", "# Fresh v0.3 run on the standard 6-person map; commands use only world.submit.", "# Generated by tests/tactics_v3_freeze.py; hash is NOT the v0.2 fingerprint.", "# Exact snapshot: time, units, buildings, supplies, projectiles, stats, RNG.", "static func expected() -> Dictionary:", "\treturn " + gd(expected), "", "static func commands() -> Array:", "\treturn ["]
    for op in result["operations"]:
        order = {key: op[key] for key in ["step", "ids", "kind", "data"]}
        line = gd(order)
        if "position" in order["data"]:
            position = order["data"]["position"]
            line = line.replace('"position": ' + gd(position), '"position": Vector2(' + ", ".join(map(repr, position)) + ")")
        lines.append("\t\t" + line + ",")
    lines += ["\t]", ""]
    Path("scripts/qa/verified_tactic_v3.gd").write_text("\n".join(lines), encoding="utf-8")
    Path("build/reports/tactics_v3_verified.json").write_text(json.dumps([result], ensure_ascii=False, indent=2), encoding="utf-8")
    print("V3_FROZEN commands=%s hash=%s alive=%s core=%s" % (len(result["operations"]), result["state_hash"], result["alive"], result["core_hp"]))


if __name__ == "__main__":
    main()
